<p>WebRTC（Web Real-Time Communications）是一项实时通讯技术，它允许网络应用或者站点，在不借助中间媒介的情况下，建立浏览器之间点对点（Peer-to-Peer）的连接，实现视频流和（或）音频流或者其他任意数据的传输。</p>
<h2 id="webrtc-应用场景" tabindex="-1"><a class="header-anchor" href="#webrtc-应用场景"><span>WebRTC 应用场景</span></a></h2>
<p>WebRTC 的能力使其适用于各种实时通信场景：</p>
<ul>
<li>点对点通讯：WebRTC 支持浏览器之间进行音视频通话，例如语音通话、视频通话等；</li>
<li>电话会议：WebRTC 可以支持多人音视频会议，例如腾讯会议、钉钉会议等；</li>
<li>屏幕共享：WebRTC 不仅可以传输音视频流，还可以用于实时共享屏幕；</li>
<li>直播：WebRTC 可以用于构建实时直播，用户可以通过浏览器观看直播内容。</li>
</ul>
